const jikanCharacterCache = new Map<
  string,
  { expiresAt: number; items: CatalogueCharacter[] }
>();

export async function searchAnimeCharacters(query: string): Promise<CatalogueCharacter[]> {
  const clean = query.trim().toLowerCase();
  if (!clean) {
    return CURATED_ANIME_CHARACTERS.slice(0, 16);
  }

  const localMatches = CURATED_ANIME_CHARACTERS.filter(
    (c) =>
      c.name.toLowerCase().includes(clean) || c.animeTitle.toLowerCase().includes(clean)
  );

  if (clean.length < 2) {
    return localMatches.length > 0 ? localMatches : CURATED_ANIME_CHARACTERS.slice(0, 12);
  }

  const cached = jikanCharacterCache.get(clean);
  if (cached && cached.expiresAt > Date.now()) {
    return cached.items;
  }

  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 3500);
    const res = await fetch(
      `https://api.jikan.moe/v4/characters?q=${encodeURIComponent(clean)}&order_by=favorites&sort=desc&limit=14`,
      { signal: controller.signal }
    );
    clearTimeout(timeout);

    if (res.ok) {
      const json: any = await res.json();
      const remoteItems: CatalogueCharacter[] = Array.isArray(json?.data)
        ? json.data
            .filter(
              (item: any) =>
                item?.mal_id &&
                item?.name &&
                item?.images?.jpg?.image_url &&
                !String(item.images.jpg.image_url).includes('questionmark')
            )
            .map((item: any) => ({
              malId: Number(item.mal_id),
              name: String(item.name),
              animeTitle: item.nicknames?.[0] ? `Also known as ${item.nicknames[0]}` : 'Anime Character',
              imageUrl: String(item.images?.webp?.image_url || item.images?.jpg?.image_url),
              favorites: Number(item.favorites || 0),
            }))
        : [];

      const merged = new Map<string, CatalogueCharacter>();
      for (const c of [...localMatches, ...remoteItems]) {
        const key = c.name.toLowerCase();
        if (!merged.has(key)) merged.set(key, c);
      }

      const finalList = Array.from(merged.values()).slice(0, 18);
      jikanCharacterCache.set(clean, {
        expiresAt: Date.now() + 1000 * 60 * 30,
        items: finalList,
      });
      return finalList;
    }
  } catch {
    // Gracefully fall back to curated anime character catalogue on offline/rate-limit
  }

  return localMatches;
}

export function isApprovedCatalogueImageUrl(url: string): boolean {
  if (!url) return false;
  if (url.startsWith('/assets/')) return true;
  if (url.startsWith('asset:')) return true;
  if (url.startsWith('/api/media/')) return true;
  if (url.startsWith('/api/demo-avatar/')) return true;
  if (url.startsWith('/api/demo-banner/')) return true;
  try {
    const parsed = new URL(url);
    const allowedHosts = [
      'cdn.myanimelist.net',
      'myanimelist.net',
      's4.anilist.co',
      'anilist.co',
    ];
    return allowedHosts.some(
      (h) => parsed.hostname === h || parsed.hostname.endsWith(`.${h}`)
    );
  } catch {
    return false;
  }
}
